function kidPrice(sku: string, band: 'western' | 'dresses' | 'ethnic'): number {
  let hash = 2166136261;
  for (let i = 0; i < sku.length; i += 1) {
    hash ^= sku.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  const n = hash >>> 0;
  const suffix = PRICE_SUFFIXES[n % PRICE_SUFFIXES.length];
  if (band === 'ethnic') return 3500 + ((n >>> 4) % 14) * 200 + suffix;
  if (band === 'dresses') return 3350 + ((n >>> 4) % 8) * 150 + suffix;
  return 3150 + ((n >>> 4) % 7) * 150 + suffix;
}

