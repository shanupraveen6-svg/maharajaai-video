function buildKidsCategory(
  titles: readonly string[],
  config: {
    idPrefix: string;
    skuPrefix: string;
    gender: 'boys' | 'girls';
    audience: 'Boys' | 'Girls';
    category: TryFocusProduct['category'];
    garmentType: TryFocusProduct['garmentType'] | ((index: number) => TryFocusProduct['garmentType']);
    imagePrefix: string;
    fabricNote: string;
    eligibleForLive: boolean;
    priceBand: 'western' | 'dresses' | 'ethnic';
    newArrivalCount: number;
  },
): TryFocusProduct[] {
  return titles.map((title, index) => {
    const num = String(index + 1).padStart(2, '0');
    const sku = `${config.skuPrefix}-${num}`;
    const imageUrl = `${config.imagePrefix}${num}.jpg`;
    const garmentType = typeof config.garmentType === 'function' ? config.garmentType(index) : config.garmentType;
    return {
      id: `${config.idPrefix}-${num}`,
      sku,
      title,
      category: config.category,
      audience: config.audience,
      gender: config.gender,
      price: kidPrice(sku, config.priceBand),
      imageUrl,
      garmentReferenceUrl: imageUrl,
      fabricNote: config.fabricNote,
      badge: index < config.newArrivalCount ? 'NEW ARRIVAL' : 'BEST SELLER',
      accent: ACCENT,
      eligibleForVideo: true,
      eligibleForLive: config.eligibleForLive,
      newArrivalOnly: false,
      createdAt: ADDED_AT,
      garmentType,
    };
  });
}

