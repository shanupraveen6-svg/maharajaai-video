function buildWomenLiveCategory(
  titles: readonly string[],
  config: {
    idPrefix: string;
    skuPrefix: string;
    category: TryFocusProduct['category'];
    garmentType: TryFocusProduct['garmentType'];
    imagePrefix: string;
    fabricNote: string;
  },
): TryFocusProduct[] {
  return titles.map((title, index) => {
    const num = String(index + 1).padStart(2, '0');
    const imageUrl = `${config.imagePrefix}${num}.jpg`;
    return {
      id: `${config.idPrefix}-${num}`,
      sku: `${config.skuPrefix}-${num}`,
      title,
      category: config.category,
      audience: 'Women',
      gender: 'women',
      price: 0,
      imageUrl,
      garmentReferenceUrl: imageUrl,
      fabricNote: config.fabricNote,
      badge: index < 12 ? 'NEW ARRIVAL' : 'BEST SELLER',
      accent: 'from-[#FAF6F0] to-[#EFE8DC]',
      eligibleForVideo: false,
      eligibleForLive: true,
      newArrivalOnly: false,
      createdAt: '2026-11-19T12:00:00.000Z',
      garmentType: config.garmentType,
    };
  });
}

