import { register } from 'node:module';
import assert from 'node:assert/strict';
register('./ts-alias-loader.mjs', import.meta.url);
for (const key of ['FIREBASE_PROJECT_ID', 'FIREBASE_CLIENT_EMAIL', 'FIREBASE_PRIVATE_KEY']) delete process.env[key];
process.env.ALLOW_MOCK_BACKEND = 'true';
process.env.OPERATOR_AUTH_SECRET = 'tv-handoff-test';
const { NextRequest } = await import('next/server.js');
const { getMockStore } = await import('../src/lib/firebase/admin.ts');
const { getVideoPass } = await import('../src/lib/maharaja/server.ts');
const { VIDEO_PROMPT_ARCHITECTURE_VERSION } = await import('../src/lib/maharaja/video-concepts.ts');
const { POST } = await import('../src/app/api/maharaja/video-pass/route.ts');
const sourceId = 'tv_vidmaster_handoff_test';
const masterUrl = 'https://storage.googleapis.com/test/master.jpg';
getMockStore().sessions.set(sourceId, { accessCode: null, clientId: 'maharaja', masterImageUrl: masterUrl, masterStoragePath: `clients/maharaja/sessions/${sourceId}/master/master.jpg`, promptArchitectureVersion: VIDEO_PROMPT_ARCHITECTURE_VERSION, templateId: 'women', conceptId: 'women-golden-courtyard', garmentType: 'saree', personPhotoStoragePath: `clients/maharaja/sessions/${sourceId}/person/reference.jpg`, garmentPhotoStoragePaths: [`clients/maharaja/sessions/${sourceId}/garment/reference-0.jpg`] });
const body = { source: 'tv-kiosk', billLast4: '1234', catalogueSku: '8IC53071', eventId: 'diwali', videoMasterUrl: masterUrl, videoReferenceSessionId: sourceId };
const request = (data) => new NextRequest('http://localhost/api/maharaja/video-pass', { method: 'POST', headers: { 'Content-Type': 'application/json', 'x-operator-key': 'tv-handoff-test' }, body: JSON.stringify(data) });
const response = await POST(request(body));
const data = await response.json();
assert.equal(response.status, 200, JSON.stringify(data));
const pass = await getVideoPass(data.pass.code);
assert.equal(pass.videoReferenceSessionId, sourceId);
assert.equal(pass.videoPromptArchitectureVersion, VIDEO_PROMPT_ARCHITECTURE_VERSION);
assert.equal(pass.videoGarmentPhotoStoragePaths.length, 1);
assert.equal(pass.videoMasterApproved, false, 'The customer approves the portrait on mobile.');
assert.equal(getMockStore().sessions.get(sourceId).accessCode, pass.code);
assert.equal((await POST(request(body))).status, 409, 'One portrait cannot be assigned to another customer pass.');
assert.equal((await POST(request({ ...body, billLast4: '' }))).status, 400);
console.log('TV video handoff passed: source ownership, garment references, current prompt version, mobile approval and single customer binding.');
