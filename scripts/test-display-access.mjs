import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import { register } from 'node:module';
register('./ts-alias-loader.mjs', import.meta.url);
for (const key of ['FIREBASE_PROJECT_ID', 'FIREBASE_CLIENT_EMAIL', 'FIREBASE_PRIVATE_KEY']) delete process.env[key];
process.env.ALLOW_MOCK_BACKEND = 'true';
process.env.OPERATOR_AUTH_SECRET = 'display-test-secret';
const { NextRequest } = await import('next/server');
const { issueDisplayToken, verifyDisplayRequest, revokeDisplayTokens } = await import('../src/lib/auth/display.ts');
const { verifyOperatorRequest } = await import('../src/lib/auth/operator.ts');
const { POST, DELETE } = await import('../src/app/api/tv/pair/route.ts');
const request = (token) => new NextRequest('http://localhost/maharaja/tv', { headers: { cookie: `maharaja_display_auth=${token}` } });
const token = await issueDisplayToken();
assert.equal(await verifyDisplayRequest(request(token)), true);
assert.equal(verifyOperatorRequest(request(token)), false, 'Display cookie cannot authorize admin requests.');
assert.equal(await verifyDisplayRequest(request(`${token}x`)), false);
const expiredPayload = token.split('.').slice(0, 2).join('.') + '.1';
const expired = `${expiredPayload}.${crypto.createHmac('sha256', process.env.OPERATOR_AUTH_SECRET).update(expiredPayload).digest('hex')}`;
assert.equal(await verifyDisplayRequest(request(expired)), false);
assert.equal((await POST(request(token))).status, 401, 'Display cannot renew itself.');
assert.equal((await DELETE(request(token))).status, 401, 'Display cannot revoke staff pairing settings.');
await revokeDisplayTokens();
assert.equal(await verifyDisplayRequest(request(token)), false, 'Revocation takes effect immediately.');
assert.equal(await verifyDisplayRequest(request(await issueDisplayToken())), true);
console.log('Display auth passed: valid, forged, expired, revoked, and admin-isolation checks.');
